package io.basat.monitoring.reading;

import io.basat.monitoring.live.LiveReading;
import io.basat.monitoring.live.LiveReadingPublisher;
import io.basat.monitoring.meter.Meter;
import io.basat.monitoring.meter.MeterRepository;
import io.basat.monitoring.meter.MeterType;
import io.basat.monitoring.site.Site;
import io.basat.monitoring.site.SiteType;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class ReadingServiceImplTest {

    private static final UUID TENANT_ID = UUID.randomUUID();
    private static final UUID SITE_ID = UUID.randomUUID();
    private static final UUID METER_ID = UUID.randomUUID();
    private static final Instant MEASURED_AT = Instant.parse("2026-11-18T10:30:00Z");
    private static final ReadingMessage MESSAGE =
            new ReadingMessage("EM-2024-001", MEASURED_AT, new BigDecimal("0.1150"));

    @Mock
    private ReadingRepository readingRepository;

    @Mock
    private MeterRepository meterRepository;

    @Mock
    private LiveReadingPublisher liveReadingPublisher;

    @InjectMocks
    private ReadingServiceImpl readingService;

    private Meter meter;

    @BeforeEach
    void createMeter() {
        Site site = new Site(TENANT_ID, "Antalya Otel", SiteType.HOTEL, null, null);
        ReflectionTestUtils.setField(site, "id", SITE_ID);  // normally generated by the database

        meter = new Meter(site, "Ana Pano", "EM-2024-001", MeterType.ELECTRICITY);
        ReflectionTestUtils.setField(meter, "id", METER_ID);
    }

    @Test
    void newReading_isPublishedToItsSite() {
        when(meterRepository.findBySerialNumber("EM-2024-001")).thenReturn(Optional.of(meter));
        when(readingRepository.save(METER_ID, MEASURED_AT, new BigDecimal("0.1150"))).thenReturn(true);

        readingService.store(MESSAGE);

        verify(liveReadingPublisher).publish(TENANT_ID, SITE_ID, new LiveReading(METER_ID, "EM-2024-001",
                MeterType.ELECTRICITY, MEASURED_AT, new BigDecimal("0.1150")));
    }

    @Test
    void repeatedReading_isNotPublishedAgain() {
        when(meterRepository.findBySerialNumber("EM-2024-001")).thenReturn(Optional.of(meter));
        when(readingRepository.save(METER_ID, MEASURED_AT, new BigDecimal("0.1150"))).thenReturn(false);

        readingService.store(MESSAGE);

        verify(liveReadingPublisher, never()).publish(any(), any(), any());
    }

    @Test
    void unknownMeter_isRejectedWithoutPublishing() {
        when(meterRepository.findBySerialNumber("EM-2024-001")).thenReturn(Optional.empty());

        assertThatThrownBy(() -> readingService.store(MESSAGE)).isInstanceOf(UnknownMeterException.class);
        verifyNoInteractions(readingRepository, liveReadingPublisher);
    }
}
